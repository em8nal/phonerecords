/** Extracts the Spotify album/track id from a `links` entry that points to open.spotify.com. */
function extractSpotifyAlbumId(links: { href: string }[] | undefined): string | null {
  if (!links) return null;
  for (const l of links) {
    const m = l.href.match(/open\.spotify\.com\/(?:album|track)\/([A-Za-z0-9]{16,})/);
    if (m) return m[1];
  }
  return null;
}

type ReleaseParams = { lang: string; slug: string };

export function generateStaticParams() {
  const langs: Language[] = ["es", "en"];
  return langs.flatMap((lang) =>
    releaseSlugs.map((slug) => ({ lang, slug }))
  );
}

function trimToLength(text: string, max: number): string {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > max * 0.6 ? cut.slice(0, lastSpace) : cut).replace(/[\s,;:.\-—]+$/, "") + "…";
}

export async function generateMetadata(
  { params }: { params: Promise<ReleaseParams> }
): Promise<Metadata> {
  const { lang, slug } = await params;
  const release = getRelease(slug);
  if (!release) return { title: "Release no encontrado" };
  const isEs = lang === "es";
  const fullDescription = isEs ? release.description.es : release.description.en;
  // Collapse paragraph breaks so the snippet reads as one line.
  const desc = trimToLength(fullDescription.replace(/\s+/g, " "), 158);
  const pageTitle = `${release.title} — ${release.artistName}`;
  return {
    title: pageTitle,
    description: desc,
    alternates: {
      canonical: `https://phonerecords.cl/${lang}/releases/${slug}`,
      languages: {
        es: `https://phonerecords.cl/es/releases/${slug}`,
        en: `https://phonerecords.cl/en/releases/${slug}`,
        "x-default": `https://phonerecords.cl/es/releases/${slug}`,
      },
    },
    openGraph: {
      type: release.type === "single" ? "music.song" : "music.album",
      siteName: "PHŌNÉ Records",
      title: pageTitle,
      description: desc,
      url: `https://phonerecords.cl/${lang}/releases/${slug}`,
      locale: isEs ? "es_CL" : "en_US",
      // Dynamic 1200x630 banner generated by opengraph-image.tsx is picked up
      // automatically by Next.js for og:image.
    },
    twitter: {
      card: "summary_large_image",
      title: pageTitle,
      description: desc,
      // Next reuses the opengraph-image.tsx banner for twitter:image (same URL as og:image).
    },
  };
}

export default async function ReleasePage({
  params,
}: {
  params: Promise<ReleaseParams>;
}) {
  const { lang, slug } = await params;
  const release = getRelease(slug);
  if (!release) notFound();

  const isEs = lang === "es";
  const description = isEs ? release.description.es : release.description.en;
  const paragraphs = description
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean);
  // Server-side answer, used for SSR/hydration; the client components re-check the clock.
  const initiallyReleased = isReleased(release.releaseDate);
  const uiLang: Language = isEs ? "es" : "en";

  const labels = isEs
    ? { back: "Volver al catálogo", tracklist: "Tracklist", credits: "Créditos", links: "Escuchar", releaseDate: initiallyReleased ? "Fecha" : "Fecha de lanzamiento", format: "Formato", label: "Sello", track: "Track" }
    : { back: "Back to catalogue", tracklist: "Tracklist", credits: "Credits", links: "Listen", releaseDate: initiallyReleased ? "Released" : "Release date", format: "Format", label: "Label", track: "Track" };

  // JSON-LD MusicAlbum schema
  const url = `https://phonerecords.cl/${lang}/releases/${slug}`;
  const albumSchema = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "MusicAlbum",
        "@id": `${url}#album`,
        name: release.title,
        url,
        datePublished: release.releaseDate,
        ...(release.cover ? { image: release.cover } : {}),
        albumReleaseType: release.type === "single"
          ? "https://schema.org/SingleRelease"
          : release.type === "ep"
          ? "https://schema.org/EPRelease"
          : "https://schema.org/AlbumRelease",
        ...(release.label ? { recordLabel: { "@type": "Organization", name: release.label } } : {}),
        byArtist: {
          "@type": "MusicGroup",
          name: release.artistName,
          url: `https://phonerecords.cl/${lang}/artistas/${release.artistSlug}`,
        },
        numTracks: release.tracklist?.length,
        ...(release.tracklist
          ? {
              track: release.tracklist.map((t) => ({
                "@type": "MusicRecording",
                name: t.title,
                ...(t.duration ? { duration: `PT${t.duration.split(":").reduce((acc, v, i, a) => acc + (i === a.length - 1 ? `${v}S` : `${v}M`), "")}` } : {}),
                ...(t.composer ? { composer: { "@type": "Person", name: t.composer } } : {}),
              })),
            }
          : {}),
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "PHŌNÉ Records", item: `https://phonerecords.cl/${lang}` },
          { "@type": "ListItem", position: 2, name: isEs ? "Catálogo" : "Catalogue", item: `https://phonerecords.cl/${lang}/catalogo` },
          { "@type": "ListItem", position: 3, name: `${release.artistName} — ${release.title}`, item: url },
        ],
      },
    ],
  };

  return (
    <main className="relative min-h-screen overflow-x-hidden noise-overlay">
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(albumSchema) }}
      />
      <Navigation />

      {/* Hero: portada desenfocada de fondo, portada nítida, h1, badge y CTA primario */}
      <ReleaseHero release={release} lang={uiLang} initialReleased={initiallyReleased} />

      <article className="max-w-[1200px] mx-auto px-6 lg:px-12 pt-12 lg:pt-16 pb-24">
        <Link
          href={`/${lang}/catalogo`}
          className="inline-flex items-center gap-2 text-sm text-muted-foreground hover:text-foreground transition-colors mb-12 group"
        >
          <ArrowLeft className="w-4 h-4 group-hover:-translate-x-1 transition-transform" />
          {labels.back}
        </Link>

        {/* Meta: la portada, el h1, el badge y el CTA viven en el hero (una sola portada grande) */}
        <header className="mb-12 lg:mb-16">
          <div className="flex flex-wrap gap-x-8 gap-y-2 text-sm font-mono text-muted-foreground uppercase tracking-widest">
            <span>{labels.releaseDate}: {release.releaseDate}</span>
            <span>{labels.format}: {release.format}</span>
            {release.label && <span>{labels.label}: {release.label}</span>}
          </div>
        </header>

        {/* Description */}
        <section className="grid lg:grid-cols-12 gap-12 lg:gap-16 mb-20">
          <div className="lg:col-span-8 space-y-6">
            {paragraphs.map((text, i) => (
              <p
                key={i}
                className={
                  i === 0
                    ? "text-lg lg:text-xl text-foreground/90 leading-relaxed"
                    : "text-base lg:text-lg text-foreground/80 leading-relaxed"
                }
              >
                {text}
              </p>
            ))}
            {release.video && (
              <div className="pt-6">
                <YouTubeEmbed youtubeId={release.video.youtubeId} title={release.video.title} />
              </div>
            )}
          </div>

          {release.links && release.links.length > 0 && (
            <aside className="lg:col-span-4">
              <h3 className="font-mono text-xs text-muted-foreground uppercase tracking-widest mb-4">
                {labels.links}
              </h3>
              <ul className="space-y-2">
                {release.links.map((link) => (
                  <li key={link.href}>
                    <a
                      href={link.href}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="inline-flex items-center gap-2 text-sm hover:text-foreground/70 transition-colors group"
                    >
                      {isEs ? link.label : link.label.replace("Escuchar", "Listen")}
                      <ExternalLink className="w-3 h-3 opacity-50 group-hover:opacity-100 transition-opacity" />
                    </a>
                  </li>
                ))}
              </ul>
            </aside>
          )}
        </section>

        {/* Spotify player (only when release has a Spotify link) */}
        {(() => {
          const spotifyId = extractSpotifyAlbumId(release.links);
          if (!spotifyId) return null;
          return (
            <section className="mb-20">
              <SpotifyAlbumEmbed albumId={spotifyId} height={352} />
            </section>
          );
        })()}

        {/* Tracklist */}
        {release.tracklist && release.tracklist.length > 0 && (
          <section className="mb-20">
            <h2 className="text-3xl lg:text-5xl font-display tracking-tight mb-12">
              {labels.tracklist}
            </h2>
            <div className="border-t border-foreground/10">
              {release.tracklist.map((t) => (
                <div
                  key={t.n}
                  className="grid grid-cols-12 gap-4 py-5 border-b border-foreground/10 items-baseline"
                >
                  <div className="col-span-1 font-mono text-xs text-muted-foreground">
                    {String(t.n).padStart(2, "0")}
                  </div>
                  <div className="col-span-9 lg:col-span-8">
                    <div className="text-base lg:text-lg">{t.title}</div>
                    {t.guests && t.guests.length > 0 && (
                      <div className="text-xs text-muted-foreground mt-1">
                        feat. {t.guests.join(", ")}
                      </div>
                    )}
                    {t.composer && (
                      <div className="text-xs text-muted-foreground mt-1">
                        comp. {t.composer}
                      </div>
                    )}
                  </div>
                  <div className="col-span-2 lg:col-span-3 text-right font-mono text-sm text-muted-foreground">
                    {t.duration}
                  </div>
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Credits */}
        {release.credits && release.credits.length > 0 && (
          <section className="mb-20">
            <h2 className="text-3xl lg:text-5xl font-display tracking-tight mb-12">
              {labels.credits}
            </h2>
            <div className="space-y-4">
              {release.credits.map((c, i) => (
                <div key={i} className="grid grid-cols-12 gap-4 py-3 border-b border-foreground/10">
                  <div className="col-span-12 sm:col-span-4 font-mono text-xs uppercase tracking-widest text-muted-foreground">
                    {c.role}
                  </div>
                  <div className="col-span-12 sm:col-span-8 text-base">{c.name}</div>
                </div>
              ))}
            </div>
          </section>
        )}

      </article>

      {/* Grilla de cierre: mismo artista primero, luego los más recientes (plan §5.7.5) */}
      <ReleaseCardGrid lang={uiLang} currentSlug={release.slug} artistSlug={release.artistSlug} />

      <FooterSection />
    </main>
  );
}
